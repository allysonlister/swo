def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build SWO software lookup tables and manage the data-entry Google Sheet.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--credentials",
        default=os.environ.get("GOOGLE_APPLICATION_CREDENTIALS"),
        metavar="JSON",
        help="Service-account key file (also via GOOGLE_APPLICATION_CREDENTIALS)",
    )
    parser.add_argument(
        "--spreadsheet",
        default=os.environ.get("SPREADSHEET_ID"),
        metavar="ID",
        help="Google Spreadsheet ID (also via SPREADSHEET_ID)",
    )
    parser.add_argument("--owl",        default=DEFAULT_OWL, metavar="PATH")
    parser.add_argument("--tsv",        default=DEFAULT_TSV, metavar="PATH")
    parser.add_argument("--lookups-dir", default=DEFAULT_LDIR, metavar="DIR",
                        help="Directory for lookup TSV output files")
    parser.add_argument("--excel",  action="store_true",
                        help="Also write lookups.xlsx (requires openpyxl)")
    parser.add_argument("--schema", action="store_true",
                        help="Generate DataHarmonizer export.js")
    parser.add_argument("--schema-dir", default=DEFAULT_SDIR, metavar="DIR",
                        help="Directory for export.js output")
    parser.add_argument("--setup",  action="store_true",
                        help="Create/refresh lookup sheets + dropdowns in Google Sheet")
    parser.add_argument("--push",   action="store_true",
                        help="Upload software.tsv to Google Sheet")
    parser.add_argument("--pull",   action="store_true",
                        help="Download Google Sheet → software.tsv")
    args = parser.parse_args()

    do_local   = True                              # always export local TSVs
    do_gs_setup = args.setup
    do_gs_push  = args.push
    do_gs_pull  = args.pull

    # Load ontology and build lookup data
    print(f"Loading {args.owl} ...")
    g = Graph()
    g.parse(args.owl)
    print(f"  {len(g)} triples loaded")

    lookup_data = build_lookup_data(g, tsv_path=args.tsv)
    for name, rows in lookup_data.items():
        print(f"  {name}: {len(rows)} entries")

    # --- Local export (always) ---
    print(f"\nExporting lookup TSVs to {args.lookups_dir} ...")
    export_lookup_tsvs(lookup_data, args.lookups_dir)

    if args.excel:
        print("Exporting Excel workbook ...")
        export_lookup_excel(lookup_data, args.lookups_dir)

    if args.schema:
        os.makedirs(args.schema_dir, exist_ok=True)
        print(f"\nGenerating export.js to {args.schema_dir} ...")
        _write_export_js(os.path.join(args.schema_dir, "export.js"))

    # --- Google Sheets ---
    if do_gs_setup or do_gs_push or do_gs_pull:
        if not args.credentials:
            print(
                "ERROR: --credentials (or GOOGLE_APPLICATION_CREDENTIALS) is required"
                " for Google Sheets operations.",
                file=sys.stderr,
            )
            sys.exit(1)
        if not args.spreadsheet:
            print(
                "ERROR: --spreadsheet (or SPREADSHEET_ID) is required"
                " for Google Sheets operations.",
                file=sys.stderr,
            )
            sys.exit(1)

        print("\nConnecting to Google Sheets ...")
        client = _get_client(args.credentials)
        spreadsheet = client.open_by_key(args.spreadsheet)
        print(f"  Opened: {spreadsheet.title}")

        # Data-row count (for validation range sizing)
        n_data_rows = 500
        if os.path.exists(args.tsv):
            with open(args.tsv) as f:
                n_data_rows = max(0, sum(1 for _ in f) - 2)

        if do_gs_setup:
            cmd_setup(spreadsheet, lookup_data, n_data_rows)
        if do_gs_push:
            cmd_push(spreadsheet, args.tsv, lookup_data)
        if do_gs_pull:
            cmd_pull(spreadsheet, args.tsv, lookup_data)


if __name__ == "__main__":
    main()
