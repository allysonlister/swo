TSV_HEADER = ["curie", "label", "iri"]


def export_lookup_tsvs(lookup_data: dict, lookups_dir: str) -> None:
    """Write one TSV file per lookup sheet to *lookups_dir*."""
    os.makedirs(lookups_dir, exist_ok=True)
    for sheet_name, rows in lookup_data.items():
        path = os.path.join(lookups_dir, f"{sheet_name}.tsv")
        with open(path, "w", newline="", encoding="utf-8") as fh:
            writer = csv.writer(fh, delimiter="\t")
            writer.writerow(TSV_HEADER)
            writer.writerows(rows)
        print(f"  {path}  ({len(rows)} entries)")


def export_lookup_excel(lookup_data: dict, lookups_dir: str) -> None:
    """Write a combined Excel workbook with one sheet per lookup."""
    try:
        import openpyxl
        from openpyxl.styles import Font, PatternFill, Alignment
        from openpyxl.utils import get_column_letter
    except ImportError:
        print("WARNING: openpyxl not installed — skipping Excel export.", file=sys.stderr)
        print("  pip install openpyxl", file=sys.stderr)
        return

    os.makedirs(lookups_dir, exist_ok=True)
    wb = openpyxl.Workbook()
    wb.remove(wb.active)   # remove default empty sheet

    header_font   = Font(bold=True, color="FFFFFF")
    header_fill   = PatternFill("solid", fgColor="4472C4")
    alt_fill      = PatternFill("solid", fgColor="DCE6F1")

    for sheet_name, rows in lookup_data.items():
        ws = wb.create_sheet(title=sheet_name.replace("Lookup_", ""))
        ws.freeze_panes = "A2"

        # Header row
        for col_idx, hdr in enumerate(TSV_HEADER, start=1):
            cell = ws.cell(row=1, column=col_idx, value=hdr)
            cell.font  = header_font
            cell.fill  = header_fill
            cell.alignment = Alignment(horizontal="center")

        # Data rows
        for row_idx, (curie, label, iri) in enumerate(rows, start=2):
            ws.cell(row=row_idx, column=1, value=curie)
            ws.cell(row=row_idx, column=2, value=label)
            ws.cell(row=row_idx, column=3, value=iri)
            if row_idx % 2 == 0:
                for col in range(1, 4):
                    ws.cell(row=row_idx, column=col).fill = alt_fill

        # Auto-fit column widths (approximate)
        col_widths = [max(len(str(r[i])) for r in [TSV_HEADER] + rows)
                      for i in range(3)]
        for col_idx, width in enumerate(col_widths, start=1):
            ws.column_dimensions[get_column_letter(col_idx)].width = min(width + 2, 50)

    path = os.path.join(lookups_dir, "lookups.xlsx")
    wb.save(path)
    print(f"  {path}")

