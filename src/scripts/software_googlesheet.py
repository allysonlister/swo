def build_label_map(lookup_data: dict) -> dict:
    """Return {label_casefold: curie} from all lookup sheets."""
    m = {}
    for rows in lookup_data.values():
        for curie, label, _iri in rows:
            m[label.casefold()] = curie
    return m


def build_curie_map(lookup_data: dict) -> dict:
    """Return {curie: label} from all lookup sheets."""
    m = {}
    for rows in lookup_data.values():
        for curie, label, _iri in rows:
            m[curie] = label
    return m


def cell_to_labels(cell: str, curie_to_label: dict) -> str:
    """Convert a '|'-separated CURIE string to '|'-separated labels."""
    if not cell:
        return ""
    parts = [p.strip() for p in cell.split("|") if p.strip()]
    return "|".join(curie_to_label.get(p, p) for p in parts)


def cell_to_curies(cell: str, label_to_curie: dict) -> str:
    """Convert a '|'-separated label string to '|'-separated CURIEs."""
    if not cell:
        return ""
    parts = [p.strip() for p in cell.split("|") if p.strip()]
    return "|".join(label_to_curie.get(p.casefold(), p) for p in parts)


