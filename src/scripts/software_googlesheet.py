def iri_to_curie(iri_str: str) -> str:
    for prefix, ns in CURIE_MAP:
        if iri_str.startswith(ns):
            return prefix + iri_str[len(ns):]
    return f"<{iri_str}>"


def curie_to_iri(curie_str: str):
    for prefix, ns in CURIE_MAP:
        if curie_str.startswith(prefix):
            return ns + curie_str[len(prefix):]
    return None


