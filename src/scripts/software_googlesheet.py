#!/usr/bin/env python3
"""
software_googlesheet.py — Build lookup tables and manage the SWO software
                          data-entry Google Sheet.

The script has two levels of functionality:

  1. Local (no Google credentials needed):
       Export per-column lookup TSV files and an optional Excel workbook.
       These are human-readable references and can be imported manually.

  2. Google Sheets (requires service-account credentials and a spreadsheet):
       --setup   Create/refresh lookup sheets and install dropdown validation.
       --push    Upload software.tsv to the 'software' tab (labels shown).
       --pull    Download 'software' tab back to software.tsv (labels → CURIEs).

Usage
-----
  # Export local lookup files only (no Google auth required):
  python software_googlesheet.py
  python software_googlesheet.py --excel        # also write lookups.xlsx

  # Full Google Sheets workflow:
  python software_googlesheet.py --setup \\
      --credentials service_account.json \\
      --spreadsheet 1BxiMVs0XRA5nFMdKvBdBZjgmUUqptlbs74OgVE2upms

  python software_googlesheet.py --push  --credentials ... --spreadsheet ...
  python software_googlesheet.py --pull  --credentials ... --spreadsheet ...

Options
-------
  --credentials FILE   Service-account JSON.  Also via GOOGLE_APPLICATION_CREDENTIALS.
  --spreadsheet ID     Google Sheet ID (from URL).  Also via SPREADSHEET_ID.
  --owl PATH           swo-edit.owl path (default: auto-detect).
  --tsv PATH           software.tsv path (default: auto-detect).
  --lookups-dir DIR    Directory to write lookup TSVs (default: src/templates/lookups/).
  --excel              Also write a combined Excel workbook (requires openpyxl).
  --setup              Refresh lookup sheets + apply data-validation dropdowns.
  --push               Upload software.tsv to the 'software' tab.
  --pull               Download 'software' tab → software.tsv.
  --schema             Generate DataHarmonizer export.js.
  --schema-dir DIR     Directory for export.js output (default: src/templates/swo/).

Note
----
  schema.yaml is now generated by onto_to_linkml_schema.py (driven by
  software_schema_spec.yaml).  Run that script separately to regenerate it.

Authentication
--------------
  Create a Google Cloud service account, download its JSON key, share the
  target spreadsheet with the service account's email (Editor role), then
  pass the JSON path via --credentials (or GOOGLE_APPLICATION_CREDENTIALS).
"""
