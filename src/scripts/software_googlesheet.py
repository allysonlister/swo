def _write_export_js(path: str) -> None:
    """
    Generate export.js for the SWO Software DataHarmonizer template.

    The label→CURIE mapping is NOT embedded here: it is built at export time
    directly from dh.schema.enums[*].permissible_values[*].meaning, which
    already carries the full mapping via schema.yaml.  This avoids duplicating
    the enum data that the script writes into schema.yaml.
    """
    # ROBOT headers and codes as JS arrays
    headers_js = ", ".join(f'"{h}"' for h in HEADERS)
    robot_js   = ", ".join(f'"{c}"' for c in ROBOT_CODES)

    # DH columns that hold enum values (0-based; DH omits the "type" column,
    # so DH col idx = HEADERS idx − 1).
    # Columns: parent(2), license(8), software interface(9), is executed in(10),
    #          developer org(11), publisher org(12), input format(13), output format(14)
    enum_dh_cols    = [2, 8, 9, 10, 11, 12, 13, 14]
    enum_dh_cols_js = ", ".join(str(c) for c in enum_dh_cols)

    js = f"""\
// SWO Software Template — DataHarmonizer export
// Auto-generated by software_googlesheet.py
//
// Converts human-readable labels in enumeration columns back to SWO CURIEs
// and emits a software.tsv-compatible ROBOT template (two header rows).
//
// The label→CURIE map is derived at runtime from dh.schema.enums so it stays
// in sync with schema.yaml automatically — no duplicate data here.
//
// Usage: load the Software schema in DataHarmonizer, enter/edit data, then
// use File > Export > Software (TSV) to download software.tsv.

// DH column indices (0-based) that contain enum labels
const ENUM_COLS = new Set([{enum_dh_cols_js}]);

// Column index of "website homepage" in DH (0-based)
const HP_COL = 7;

export default {{
  Software: {{
    fileType: "tsv",
    status: "published",
    method: function (dh) {{
      // Build title→CURIE map from schema enum meanings at export time.
      // permissible_values keys are CURIEs; pv.title holds the human-readable
      // label shown in DataHarmonizer.  Map title→meaning so cells containing
      // labels are converted to CURIEs on export.
      const LABEL_TO_CURIE = {{}};
      for (const enumDef of Object.values(dh.schema.enums || {{}})) {{
        for (const [_curie, pv] of Object.entries(
          enumDef.permissible_values || {{}}
        )) {{
          if (pv.title && pv.meaning) LABEL_TO_CURIE[pv.title] = pv.meaning;
        }}
      }}

      // Row 1: human-readable column headers (ROBOT template row 1)
      const HEADERS = [{headers_js}];

      // Row 2: ROBOT template codes (row 2)
      const ROBOT_CODES = [{robot_js}];

      const output = [HEADERS, ROBOT_CODES];

      for (const inputRow of dh.getTrimmedData(dh.hot)) {{
        // DH rows lack the "type" column (index 0 in HEADERS).
        // Output row is shifted right by 1; type = "class" is prepended.
        const outputRow = new Array(HEADERS.length).fill("");
        outputRow[0] = "class"; // TYPE column for ROBOT

        for (let dhCol = 0; dhCol < inputRow.length; dhCol++) {{
          let val = (inputRow[dhCol] || "").trim();
          const robotCol = dhCol + 1; // shift for "type"

          if (ENUM_COLS.has(dhCol) && val) {{
            // Convert pipe-separated labels → CURIEs via schema meanings
            val = val
              .split("|")
              .map((v) => {{
                const t = v.trim();
                return LABEL_TO_CURIE[t] !== undefined ? LABEL_TO_CURIE[t] : t;
              }})
              .join("|");
          }}

          if (dhCol === HP_COL && val) {{
            // Homepage: wrap in double-quotes for ROBOT DataHasValue encoding
            val = '"' + val.replace(/"/g, "") + '"';
          }}

          outputRow[robotCol] = val;
        }}

        output.push(outputRow);
      }}

      return output;
    }},
  }},
}};
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(js)
    print(f"  {path}")


