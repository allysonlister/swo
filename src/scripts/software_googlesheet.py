def is_deprecated(g: Graph, uri: URIRef) -> bool:
    """Return True if *uri* carries owl:deprecated true."""
    return bool(g.value(uri, OWL.deprecated))


def all_subclasses(g: Graph, root: URIRef) -> set:
    """Return all transitive subclasses of *root* (not including root itself)."""
    seen: set = set()
    queue = [s for s in g.subjects(RDFS.subClassOf, root) if isinstance(s, URIRef)]
    while queue:
        cls = queue.pop()
        if cls in seen:
            continue
        seen.add(cls)
        queue.extend(
            s for s in g.subjects(RDFS.subClassOf, cls) if isinstance(s, URIRef)
        )
    return seen


def classes_for_property(g: Graph, prop_iri: str, ns_fallbacks: list) -> set:
    """
    Return the set of URIRef classes that are valid fillers for *prop_iri*.

    Strategy:
      1. Find rdfs:range declarations on the property.
      2. Collect transitive subclasses of each range root.
      3. Add all classes found in *ns_fallbacks* namespaces (supplement /
         fallback when no range is declared or the range is very broad).
    """
    prop = URIRef(prop_iri)
    roots = {o for o in g.objects(prop, RDFS.range) if isinstance(o, URIRef)}

    result: set = set()
    for root in roots:
        result.add(root)
        result.update(all_subclasses(g, root))

    # Namespace fallback / supplement.
    # After collecting namespace-fallback classes, also recurse into their
    # transitive subclasses — this catches SWO:-namespace subclasses of
    # SWOB:/EDAM: classes that wouldn't be found by range traversal alone.
    fallback_new: set = set()
    for ns in ns_fallbacks:
        for s in g.subjects(RDF.type, OWL.Class):
            if isinstance(s, URIRef) and str(s).startswith(ns) and s not in result:
                result.add(s)
                fallback_new.add(s)
    for s in fallback_new:
        result.update(all_subclasses(g, s))

    return result


def individuals_in_namespace(g: Graph, namespace: str) -> list:
    """Return sorted [(curie, label, iri)] for NamedIndividuals in *namespace*."""
    items = []
    for ind in g.subjects(RDF.type, OWL.NamedIndividual):
        if not (isinstance(ind, URIRef) and str(ind).startswith(namespace)):
            continue
        if is_deprecated(g, ind):
            continue
        label = g.value(ind, RDFS.label)
        if not label:
            continue
        curie = iri_to_curie(str(ind))
        if curie.startswith("<"):
            continue
        items.append((curie, str(label), str(ind)))
    return sorted(items, key=lambda x: x[1].casefold())


def classes_to_lookup_rows(g: Graph, cls_set: set) -> list:
    """
    Given a set of class URIRefs, return sorted [(curie, label, iri)] rows.
    Only classes with an rdfs:label and a valid CURIE are included.
    """
    items = []
    for cls in cls_set:
        if not isinstance(cls, URIRef):
            continue
        if is_deprecated(g, cls):
            continue
        label = g.value(cls, RDFS.label)
        if not label:
            continue
        curie = iri_to_curie(str(cls))
        if curie.startswith("<"):
            continue
        items.append((curie, str(label), str(cls)))
    return sorted(items, key=lambda x: x[1].casefold())


def build_parent_lookup(g: Graph) -> list:
    """
    Return sorted [(curie, label, iri)] for SWO:0000001 (software) and ALL
    of its transitive subclasses.  These are valid values for the 'parent'
    column.
    """
    root = URIRef("http://www.ebi.ac.uk/swo/SWO_0000001")
    all_sw = {root} | all_subclasses(g, root)
    return classes_to_lookup_rows(g, all_sw)


def supplement_from_tsv(g: Graph, lookup_data: dict, tsv_path: str) -> None:
    """
    Scan *tsv_path* and, for each dropdown column, add any class that is
    referenced in the data but not yet in the corresponding lookup.  This
    catches ontology classes that are in use but fall outside the range /
    namespace heuristics (e.g. SWO:0000139 'web content search' is a subclass
    of an EDAM operation class rather than an OBI objective).

    Only class-based lookups are supplemented (not LK_ORGS, which uses
    NamedIndividuals, and not LK_SOFTWARE, which is built from the full
    ontology hierarchy).
    """
    if not os.path.exists(tsv_path):
        return

    # col index → lookup key (class-based lookups only)
    _supplement_cols = {
        COL_LIC:    LK_LICENSES,
        COL_IFACE:  LK_IFACES,
        COL_EXEC:   LK_ENVS,
        COL_INFMT:  LK_FORMATS,
        COL_OUTFMT: LK_FORMATS,
    }

    with open(tsv_path, newline="", encoding="utf-8") as fh:
        rows = list(csv.reader(fh, delimiter="\t"))

    for col_idx, lk_key in _supplement_cols.items():
        existing = {row[0] for row in lookup_data[lk_key]}
        additions: list = []
        seen_new: set = set()
        for row in rows[2:]:            # skip both header rows
            if len(row) <= col_idx:
                continue
            for val in row[col_idx].split("|"):
                val = val.strip()
                if not val or val in existing or val in seen_new:
                    continue
                iri = curie_to_iri(val)
                if not iri:
                    continue
                label = g.value(URIRef(iri), RDFS.label)
                if label:
                    additions.append((val, str(label), iri))
                    seen_new.add(val)

        if additions:
            combined = lookup_data[lk_key] + additions
            lookup_data[lk_key] = sorted(combined, key=lambda x: x[1].casefold())
            print(f"  supplement: added {len(additions)} entries to {lk_key} from TSV")


def build_lookup_data(g: Graph, tsv_path: str = "") -> dict:
    """
    Query the ontology and return:
      { lookup_sheet_name: [(curie, label, iri), ...] }

    Column → property → lookup:
      parent            SWO:0000001 and all subclasses          → LK_SOFTWARE
      license           has_license (SWO:has_license)           → LK_LICENSES
      software interface SWO_0004001 (has interface)            → LK_IFACES
      is executed in    SWO_0040005 (is executed in)            → LK_ENVS
      dev/pub org       —  NamedIndividuals in SWOO namespace   → LK_ORGS
      data input/output SWO_0004002 (has format specification)  → LK_FORMATS
    """
    SWO = "http://www.ebi.ac.uk/swo/"

    # --- Licenses ---
    # has_license has no rdfs:range; fall back to the SWOL namespace entirely.
    lic_classes = classes_for_property(
        g,
        SWO + "has_license",
        ns_fallbacks=["http://www.ebi.ac.uk/swo/license/SWO_"],
    )
    license_rows = classes_to_lookup_rows(g, lic_classes)

    # --- Interfaces ---
    # range = SWO_9000050 ("software interface"); all subclasses live in SWOI.
    iface_classes = classes_for_property(
        g,
        SWO + "SWO_0004001",
        ns_fallbacks=["http://www.ebi.ac.uk/swo/interface/SWO_"],
    )
    iface_rows = classes_to_lookup_rows(g, iface_classes)

    # --- Execution environments ---
    # range = OBI_0200000 / OBI_0200111; SWO-specific subclasses live in SWOB.
    env_classes = classes_for_property(
        g,
        SWO + "SWO_0040005",
        ns_fallbacks=["http://www.ebi.ac.uk/swo/objective/SWO_"],
    )
    env_rows = classes_to_lookup_rows(g, env_classes)

    # --- Organizations (named individuals, not classes) ---
    org_rows = individuals_in_namespace(
        g, "http://www.ebi.ac.uk/swo/organization/SWO_"
    )

    # --- Data formats ---
    # range = IAO_0000098 ("data item in BFO"); SWO formats live in SWOD,
    # plus any EDAM format classes imported into the ontology.
    fmt_classes = classes_for_property(
        g,
        SWO + "SWO_0004002",
        ns_fallbacks=[
            "http://www.ebi.ac.uk/swo/data/SWO_",
            "http://edamontology.org/format_",
        ],
    )
    fmt_rows = classes_to_lookup_rows(g, fmt_classes)

    # --- Software subclasses (parent column) ---
    sw_rows = build_parent_lookup(g)

    lookup_data = {
        LK_SOFTWARE: sw_rows,
        LK_LICENSES: license_rows,
        LK_IFACES:   iface_rows,
        LK_ENVS:     env_rows,
        LK_ORGS:     org_rows,
        LK_FORMATS:  fmt_rows,
    }

    # Supplement with any classes used in the actual TSV but missed by heuristics
    if tsv_path:
        supplement_from_tsv(g, lookup_data, tsv_path)

    return lookup_data

